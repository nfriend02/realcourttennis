/**
 * Headless balance simulation (07 §8.13): Bot Player vs NPC for every stage.
 * Usage: npm run sim -- [matchesPerCell]
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { plainMarkdown } from './docs/plainMarkdown';
import { aiLevel, CHARACTERS, npcCharacterFor, STAGES } from '../src/data/gameData';
import { SeededRandom } from '../src/game/core/random';
import { PlayerBot, type BotProfile } from '../src/game/match/bot';
import { MatchModel, type PointEndReason } from '../src/game/match/matchModel';

const matches = Number(process.argv[2] ?? 200);
const bots: { name: string; profile: BotProfile }[] = [
  { name: 'Skilled (40 ms / 0.95)', profile: { timingSigmaSec: 0.04, strokeAccuracy: 0.95 } },
  { name: 'Average (70 ms / 0.85)', profile: { timingSigmaSec: 0.07, strokeAccuracy: 0.85 } },
  { name: 'Beginner (100 ms / 0.70)', profile: { timingSigmaSec: 0.1, strokeAccuracy: 0.7 } },
];

interface Cell {
  wins: number;
  rally: number;
  points: number;
  reasons: Record<string, number>;
  quality: Record<string, number>;
}

const rows: string[] = [];
const detail: string[] = [];
const started = Date.now();
for (const bot of bots) {
  const winRow: string[] = [];
  for (const stage of STAGES) {
    const cell: Cell = { wins: 0, rally: 0, points: 0, reasons: {}, quality: {} };
    for (let i = 0; i < matches; i++) {
      const seed = stage.stageId * 100003 + i * 7919 + bot.profile.strokeAccuracy * 1000;
      const player = CHARACTERS[i % CHARACTERS.length];
      const m = new MatchModel({ player, npc: npcCharacterFor(player.id, stage.npcSlot), hand: 'right', level: aiLevel(stage.npcLevel), ballSpeedMul: stage.ballSpeedMul, seed });
      const b = new PlayerBot(bot.profile, new SeededRandom(seed ^ 0x5bd1e995));
      for (let k = 0; k < 120 * 900 && !m.matchOver; k++) {
        b.update(m);
        m.tick(1 / 120);
        for (const e of m.drainEvents()) {
          if (e.type === 'point_end') {
            cell.points++;
            cell.rally += m.rally;
            cell.reasons[e.reason] = (cell.reasons[e.reason] ?? 0) + 1;
          } else if (e.type === 'player_hit') {
            cell.quality[e.judgment.quality] = (cell.quality[e.judgment.quality] ?? 0) + 1;
          }
        }
      }
      if (m.winner === 'player') cell.wins++;
    }
    winRow.push(`${((cell.wins / matches) * 100).toFixed(0)}%`);
    const reasons = (Object.keys(cell.reasons) as PointEndReason[]).map((r) => `${r} ${((cell.reasons[r] / cell.points) * 100).toFixed(0)}%`).join(', ');
    const qTotal = Object.values(cell.quality).reduce((a, b) => a + b, 0) || 1;
    const quality = ['perfect', 'great', 'good', 'early', 'late'].map((q) => `${q} ${(((cell.quality[q] ?? 0) / qTotal) * 100).toFixed(0)}%`).join(', ');
    detail.push(`| ${bot.name} | ${stage.stageId} | ${(cell.rally / Math.max(1, cell.points)).toFixed(2)} | ${quality} | ${reasons} |`);
  }
  rows.push(`| ${bot.name} | ${winRow.join(' | ')} |`);
}

const md = `# Balance Simulation Report

* Matches per cell: ${matches}
* Generated by \`npm run sim\` (${((Date.now() - started) / 1000).toFixed(1)} s)
* Target (07 §8.13): Skilled S1 >= 95%, S5 >= 80%, S10 55-70% / Average S1 >= 85%, S5 55-70%, S10 30-45% / Beginner S1 >= 65%, S5 35-50%, S10 <= 25%

## Player Win Rate by Stage

| Bot | ${STAGES.map((s) => `S${s.stageId}`).join(' | ')} |
| --- | ${STAGES.map(() => '---').join(' | ')} |
${rows.join('\n')}

## Detail

| Bot | Stage | Avg Rally | Player Hit Quality | Point End Reasons |
| --- | --- | --- | --- | --- |
${detail.join('\n')}
`;

mkdirSync('docs/reports', { recursive: true });
writeFileSync('docs/reports/balance.md', plainMarkdown(md));
console.log(md);
